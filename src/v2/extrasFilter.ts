/** 文件名级特典硬过滤（"机械铁案层"）。词边界匹配、大小写不敏感。
 *
 *  ── 唯一读取方：`v2/subtitleJudge.ts` 的规则 0（2026-08-13 用户裁决）─────────────
 *  用户原话：「特典都完全不算在找字幕的范围」。命中即 `needs_subtitle=0` +
 *  `skip_reason='extra'`，该文件从此不进字幕工作台。判据为什么落在 judge 而不是扫描期或
 *  工作台谓词，见 subtitleJudge.ts 头部规则 0 那一段。
 *
 *  🔴 只收"绝无剧情"的映像/菜单/预告类标记——SP/OVA/OAD/Special 是灰区（时长/S0 才能判），
 *  **绝不进这张铁案表**（否则会误杀有字幕的剧情向 OAD）。
 *
 *  ── 为什么这张表值得留着，而"解析不出季集就不找字幕"那条更简单的规则不行 ──────────
 *  2026-08-13 生产库实测（645 文件），这是本裁决唯一的立论依据：
 *   · 本表在**全库**命中 16 个，其中有季集号的 **0 个**（零误伤），16 个时长 91–179s，
 *     全是 NCOP/NCED/PV/menu——判准。
 *   · 而 `season/episode` 解析为 NULL 的 TV 文件有 **79 个**，本表只认其中 16 个；
 *     剩下 **63 个是真剧集**（26 个 Re:ZERO 正片 ~1500s、12 个 Violet Evergarden 正片
 *     ~1420s、25 个官方短篇 spinoff 151s），**且这 63 个全部 sub_status='covered'**
 *     ——它们磁盘上已经有中文字幕，是不可能更硬的"这是真内容"的证据。
 *  所以"解析不出季集 ⇒ 不找字幕"会**误杀 63 个真剧集**（其中 38 个正片长度）。
 *  解析器在正常剧集上失败是常态（括号数字 `[01]`、日文 `第01話` 都能让它失败），
 *  拿它当特典判据是把两件不相干的事合并。标记表会过期，但它**过期的方向是漏判**
 *  （新标记没收进来 → 白找一次字幕）；简单规则失效的方向是**误杀**（永久不找）。
 *  两种代价不对称，故取标记表。
 *
 *  ── 🔴 两档标记：为什么 PV/CM/Trailer/Preview/Menu 必须要求方括号包裹（审计抓到的误杀）──
 *  上一轮的立论是「扫全库 645 命中 16，其中有季集号的 0 个 —— 零误伤」。这个数字复现无误，
 *  但它证明的是「**这批文件**没被误伤」，**不是「规则不会误伤」**。把样本属性当成规则属性
 *  用，正是本仓的病 B。审计用真函数跑常见真实片名，当场反驳：
 *      Trailer Park Boys - S01E01 - Take Your Little Gun....mkv   ← 带完整季集号的真剧集
 *      Trailer.Park.Boys.S05E03.1080p.BluRay.mkv                  ← 同上
 *      Preview.to.a.Kill.S02E04.mkv                               ← 同上
 *      The.Menu.2022.1080p.BluRay.x264.mkv                        ← 一部真电影（2022）
 *      CM.Punk.Best.in.the.World.2012.mkv                         ← 人名
 *      Show.S01E05.PV.Cut.mkv
 *  前三行**带完整 S01E01 季集号**，直接反驳了「有季集号的 0 个」那条推论。
 *  误判方向恰是本表自己认定为不可接受的那个：**误杀（永久不找）**——而 `extras_exemptions`
 *  翻案表已删，用户**没有任何界面手段翻案**，"改文件名"不是补救（没人会去重命名一部
 *  命名正确的 The.Menu.2022.mkv）。
 *
 *  两档的判据是**这个词有没有别的意思**，不是拍脑袋分组：
 *   · NCOP / NCED 是**压制圈行话**（no-credit opening/ending）。它们在自然语言里不是词，
 *     除了"无字幕 OP/ED"没有第二种意思，裸词边界匹配已经足够安全。
 *   · Menu / PV / CM / Trailer / Preview 全都是**普通英文词**（菜单 / 预览 / 广告 / 预告片），
 *     可以合法地出现在剧名、人名、电影名里——上面六行反例每一行都是这么来的。
 *     对这五个要求 `[...]` 整体包裹：方括号在发布命名约定里是**结构分隔符**，
 *     `[PV]` `[menu 01]` 表达的是"这是一个 PV 片段"，而不是标题里恰好有 PV 这个词。
 *
 *  为什么**不选**审计给的另一个方向「时长下限」（生产库实测否掉的，不是嫌麻烦）：
 *   · 时长根本分不开。16 个真命中是 91–179s，而同库有 **25 个真内容也落在这个带内**
 *     （Re Puchi 官方短篇 spinoff，151s，且 `sub_status='covered'` ——磁盘上已有中文字幕，
 *     是不可能更硬的"这是真内容"证据）。任何能盖住 179s 的下限都会连它们一起误杀，
 *     等于把误杀从"名字像特典的"扩大到"所有短片"。实测：<=180s 共 41 个文件，
 *     16 个是真命中、**25 个是真内容**。
 *   · 判据不可得。judge 的谓词是 `needs_subtitle IS NULL` ——**判过一次就永不重判**，
 *     而 `duration_sec` 由 probe 阶段（扫描期，daemonV2:1720）写。两者没有先后保证，
 *     probe 失败/未探时该列为 NULL。拿"缺席即放行"处理会让规则时灵时不灵，
 *     拿"缺席即命中"处理就是拿信息缺失当结论——正是 C40「NULL 不得判死」的铁律所禁。
 *   · 加时长会把一个**文件名事实**变成**文件名+磁盘探测事实**的合取，违反规则 0 落在
 *     judge（"不探磁盘"，D8/C27）的前提。
 *  方括号方案零新增判据、零新增列依赖，纯收紧现有正则，故取它。
 *
 *  ⚠️ 收紧的代价是**漏判方向**的：`Show PV.mkv`（无方括号的真特典）现在会被放走，白找一次
 *  字幕。这是本表开头就写明的、可接受的那个方向；反过来的误杀不可接受。生产库实测这次收紧
 *  **命中数不变（16 → 16）**：0 个原命中被放走、0 个新增命中。 */
/** 压制圈行话：不是自然语言词，裸词边界匹配即安全。 */
const JARGON_MARKERS = ['NCOP', 'NCED']
/** 普通英文词：可以合法出现在剧名/人名/片名里，**必须**由方括号整体包裹才算标记。 */
const BRACKETED_MARKERS = ['Menu', 'PV', 'CM', 'Trailer', 'Preview']

/** @param filePath 文件名或全路径（内部只看 basename）。 */
export function isMechanicalExtra(filePath: string): boolean {
  const base = filePath.split('/').pop() ?? filePath
  // 行话档 —— 词边界：marker 左侧必须是非字母数字或串首，右侧必须是非字母或串尾，
  // 同时允许 'NCOP01' 这类真实编号后缀命中。
  if (JARGON_MARKERS.some((m) => new RegExp(`(^|[^A-Za-z0-9])${m}([^A-Za-z]|$)`, 'i').test(base))) {
    return true
  }
  // 普通词档 —— 必须 `[marker]` 整体包裹，可带编号与空白：`[PV]` `[PV 01]` `[menu01]`。
  // 编号**只许跟在词后**（`[PV02]` 是 PV 第 2 段）；不放宽成 `[^\]]*`，否则
  // `[Trailer Park Boys]` 这种把剧名塞进方括号的命名会重新落回误杀。
  return BRACKETED_MARKERS.some((m) => new RegExp(`\\[\\s*${m}\\s*\\d*\\s*\\]`, 'i').test(base))
}
